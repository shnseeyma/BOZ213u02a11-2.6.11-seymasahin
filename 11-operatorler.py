eklenecek_saat = toplam_dakika // 60
bitis_dakikasi = toplam_dakika % 60
toplam_saat = hour + eklenecek_saat
bitis_saati = toplam_saat % 24
print(bitis_saati, bitis_dakikasi, sep=":")
